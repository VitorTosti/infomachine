const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const app = fs.readFileSync(`${__dirname}/mac-ui/app.js`, 'utf8');
const state = { equipmentType: 'Notebook', device3u: null, info: { modelo: 'Host PC', cpu: 'i7', ram: '16GB', disco: '256GB', bateria: '90%' } };
const context = vm.createContext({ state });
vm.runInContext(app.slice(app.indexOf('function productDescription('), app.indexOf('function batteryWithoutCycles(')) + app.slice(app.indexOf('function labelContextFromCreate('), app.indexOf('function applyGradeFromReference(')), context);
const monitor = context.labelContextFromCreate({ produto: { descricao: 'Monitor Dell 24"' }, serial: 'MON123', device3u: { modelo: 'old iPhone' } });
assert.equal(monitor.equipmentType, 'Monitor');
assert.equal(monitor.info.ram, '');
assert.equal(monitor.info.serial, 'MON123');
const phone = context.labelContextFromCreate({ produto: { descricao: 'iPad 9' }, serial: 'IPAD123' });
assert.equal(phone.info.disco, '');
assert.equal(phone.info.cpu, '');
assert.equal(state.info.disco, '256GB', 'Host information must remain intact');
const notebook = context.labelContextFromCreate({ produto: { descricao: 'Notebook Lenovo' }, serial: 'NB123' });
assert.equal(notebook.info.ram, '16GB');
state.equipmentType = 'Celular';
state.info = { disco: '64GB', ram: '3GB' };
const manual = context.labelContextFromCreate({ produto: { descricao: 'iPad 9' }, serial: 'IPAD123' });
assert.equal(manual.info.disco, '64GB', 'Keep phone-specific manual data');
console.log('Equipment context isolation tests passed.');
